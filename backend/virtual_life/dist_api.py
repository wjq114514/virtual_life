"""Distribution endpoints for the Linux desktop host client.

Downloads are gated by the same bearer token as the rest of the API, so a seat
only receives a client whose runtime it already authenticates to. Uploads
additionally require ``[dist] upload_secret``: a leaked ``api_token`` must not be
able to replace the client that seats download later.

Artifacts are owner-managed files in ``[dist] directory``. Nothing here is
generated by the runtime, and the manifest is derived from the directory
contents, so publishing a new client is an upload with no restart.
"""

from __future__ import annotations

import hashlib
import hmac
import re
from datetime import UTC, datetime
from pathlib import Path

from fastapi import APIRouter, File, Form, UploadFile
from fastapi.responses import FileResponse
from pydantic import BaseModel, ConfigDict, Field

from .coordinator import DomainError
from .settings import Settings

CHUNK_SIZE = 1024 * 1024
_VERSION_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)([a-zA-Z0-9.\-+]*)$")
_WHEEL_RE = re.compile(
    r"^virtual_life_linux-(?P<version>\d+\.\d+\.\d+[a-zA-Z0-9.\-+]*?)-py3-none-any\.whl$"
)


def is_wheel_name(name: str) -> bool:
    return _WHEEL_RE.match(name) is not None


def version_key(version: str) -> tuple[int, int, int, int, str]:
    """Sort key where a final release outranks its own prereleases."""
    match = _VERSION_RE.match(version)
    if match is None:
        return (0, 0, 0, 1, "")
    tail = match.group(4)
    return int(match.group(1)), int(match.group(2)), int(match.group(3)), 1 if tail else 2, tail


class DistPackage(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)

    version: str
    wheel: str
    sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    size_bytes: int = Field(gt=0)
    released_at: str
    requires_python: str = ">=3.12"
    runtime_version: str | None = None


class DistManifest(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)

    dist_version: str = "1.0"
    default_version: str
    packages: list[DistPackage]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while True:
            chunk = handle.read(CHUNK_SIZE)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


def _iso(timestamp: float) -> str:
    return datetime.fromtimestamp(timestamp, UTC).isoformat().replace("+00:00", "Z")


def _entry_for(path: Path) -> DistPackage:
    match = _WHEEL_RE.match(path.name)
    stat = path.stat()
    version = match.group("version") if match else "0.0.0"
    signature = sha256_file(path) if match else "0" * 64
    return DistPackage(
        version=version,
        wheel=path.name,
        sha256=signature,
        size_bytes=stat.st_size,
        released_at=_iso(stat.st_mtime),
    )


def build_dist_router(settings: Settings) -> APIRouter:
    directory = Path(settings.dist_directory).expanduser()
    # Entries are cached per (mtime, size) so listing never re-hashes a wheel
    # that has not changed.
    cached: dict[str, tuple[float, int, DistPackage]] = {}

    router = APIRouter(prefix="/dist", tags=["distribution"])

    def _wheel_files() -> list[Path]:
        if not directory.is_dir():
            return []
        return [path for path in sorted(directory.iterdir()) if is_wheel_name(path.name)]

    def _manifest() -> DistManifest:
        packages: list[DistPackage] = []
        for path in _wheel_files():
            stat = path.stat()
            fingerprint = (stat.st_mtime, stat.st_size)
            hit = cached.get(path.name)
            if hit is not None and hit[:2] == fingerprint:
                packages.append(hit[2])
                continue
            entry = _entry_for(path)
            cached[path.name] = (stat.st_mtime, stat.st_size, entry)
            packages.append(entry)
        if not packages:
            raise DomainError(404, "dist_empty", "No client packages are published yet")
        packages.sort(key=lambda item: version_key(item.version))
        return DistManifest(default_version=packages[-1].version, packages=packages)

    @router.get("/manifest.json", response_model=DistManifest)
    def manifest() -> dict:
        return _manifest().model_dump(mode="json")

    @router.get("/packages/{filename}")
    def download(filename: str) -> FileResponse:
        if not is_wheel_name(filename):
            raise DomainError(400, "dist_bad_name", "Not a published wheel filename")
        target = (directory / filename).resolve()
        if not target.is_relative_to(directory.resolve()) or not target.is_file():
            raise DomainError(404, "dist_missing", "No such client package")
        return FileResponse(path=target, filename=filename, media_type="application/octet-stream")

    @router.post("/packages", status_code=201, response_model=DistPackage)
    async def upload(
        upload_secret: str = Form(...),
        file: UploadFile = File(...),
    ) -> dict:
        if not settings.dist_upload_secret.strip():
            raise DomainError(503, "dist_upload_disabled", "[dist] upload_secret is not configured")
        if not hmac.compare_digest(upload_secret.encode(), settings.dist_upload_secret.encode()):
            raise DomainError(403, "dist_upload_forbidden", "Invalid dist upload secret")
        stem = Path(file.filename or "upload.whl").name
        if not is_wheel_name(stem):
            raise DomainError(
                400,
                "dist_bad_name",
                "Upload virtual_life_linux-<version>-py3-none-any.whl",
            )
        directory.mkdir(parents=True, exist_ok=True)
        target = (directory / stem).resolve()
        if not target.is_relative_to(directory.resolve()):
            raise DomainError(400, "dist_bad_name", "Not a valid wheel filename")
        if (
            len([path for path in _wheel_files() if path.name != stem])
            >= settings.dist_max_packages
        ):
            raise DomainError(409, "dist_limit_exceeded", "Too many published packages")
        written = 0
        digest = hashlib.sha256()
        try:
            with target.open("wb") as handle:
                while True:
                    chunk = await file.read(CHUNK_SIZE)
                    if not chunk:
                        break
                    written += len(chunk)
                    if written > settings.dist_max_bytes:
                        raise DomainError(413, "dist_too_large", "Package exceeds [dist] max_bytes")
                    digest.update(chunk)
                    handle.write(chunk)
        finally:
            await file.close()
        cached.pop(stem, None)
        return _entry_for(target).model_dump(mode="json")

    return router
